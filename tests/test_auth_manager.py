async def test_feed_message_password_happy_path(manager, bot, monkeypatch):
    await manager.ensure_authorized(100)
    machine = manager._machines[100]
    await machine.send("password_needed")
    assert machine.password_wait in machine.configuration

    keys = machine._pending_keys
    encrypted = ecies_compat.encrypt(keys.pk, b"top-secret-2fa").hex()

    session = await manager.feed_message(100, AuthEvent(55, encrypted))
    assert session is not None
    assert machine.is_authorized
    assert session.user_client.authorized  # sign_in was really called
    assert bot.deleted  # pk instruction message and user message were deleted


async def test_feed_message_not_encrypted_restarts_keys(manager, bot):
    await manager.ensure_authorized(100)

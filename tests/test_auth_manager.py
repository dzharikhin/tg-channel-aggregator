async def test_dead_qr_waiter_is_revived_on_tick(manager, bot):
    await manager.ensure_authorized(100)
    machine = manager._machines[100]
    machine._qr_task.cancel()
    await asyncio.sleep(0.05)  # let the cancellation settle: waiter is dead now
    qr = machine._qr_login
    qr._hang = False
    qr._wait_result = object()  # a fresh waiter returns at once (scan completed)

    await manager.ensure_authorized(100)  # tick sees dead waiter -> qr_expired
    await eventually_authorized(machine)
    assert "Actual until" in texts(bot)[0]
    assert bot.edited  # qr was regenerated by editing the existing message


async def eventually_authorized(machine, timeout=2.0):
    loop = asyncio.get_running_loop()
    deadline = loop.time() + timeout
    while loop.time() < deadline:
        if machine.is_authorized:
            return
        await asyncio.sleep(0.01)
    pytest.fail("machine did not become authorized")



class AuthEvent:
    """Minimal stand-in for telethon NewMessage.Event."""

    class _M:
        def __init__(self, mid, text):
            self.id = mid
            self.message = text

    def __init__(self, mid, text):
        self.message = AuthEvent._M(mid, text)



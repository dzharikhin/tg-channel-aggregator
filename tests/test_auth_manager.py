async def test_feed_message_session_expired_restarts_flow(manager, bot, monkeypatch):
    from telethon.errors import SessionExpiredError

    await manager.ensure_authorized(100)
    machine = manager._machines[100]
    await machine.send("password_needed")
    keys = machine._pending_keys

    async def expired_sign_in(password=None):
        raise SessionExpiredError(request=None)

    monkeypatch.setattr(machine.session.user_client, "sign_in", expired_sign_in)

    ev = AuthEvent(60, ecies_compat.encrypt(keys.pk, b"pass").hex())
    assert await manager.feed_message(100, ev) is None
    # flow restarts via qr on the next tick instead of looping on a dead session
    assert machine.idle in machine.configuration
    await manager.ensure_authorized(100)
    assert machine.qr_sent in machine.configuration


